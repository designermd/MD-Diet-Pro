    public static String quantityHint(int meal, int calories) {
        double scale = Math.max(0.75, Math.min(1.45, calories / 1850.0));
        if (meal == 0) return scale < 0.9 ? "الخبز/الشوفان: حصة صغيرة" : scale < 1.15 ? "الخبز: حوالي ½ رغيف أو الحصة المكتوبة" : "زد الحصة قليلاً حسب هدفك";
        if (meal == 1) return "المكسرات إن وُجدت: 15–25غ";
        if (meal == 2) {
            int protein = (int)(Math.round((160 * scale)/10.0)*10);
            return "البروتين تقريباً " + protein + "غ، والنشويات حسب الكمية المكتوبة";
        }
        return "خليه خفيف، والعشاء اختياري إذا ما في جوع حقيقي";
    }

