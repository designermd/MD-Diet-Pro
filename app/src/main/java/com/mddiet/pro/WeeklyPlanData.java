    public static String quantityHint(int meal, int calories) {
        double scale = Math.max(0.75, Math.min(1.45, calories / 1850.0));
        if (meal == 0) {
            return scale < 0.9 ? "خبز: ¼–½ رغيف" : scale < 1.15 ? "خبز: حوالي ½ رغيف" : "خبز: ½–1 رغيف";
        }
        if (meal == 1) {
            return "المكسرات إن وُجدت: 20–30غ";
        }
        if (meal == 2) {
            int protein = (int)(Math.round((180 * scale)/10.0)*10);
            int starch = Math.max(4, Math.min(9, (int)Math.round(6*scale)));
            return "بروتين: حوالي " + protein + "غ • رز/نشويات: حوالي " + starch + " ملاعق مطبوخة";
        }
        return "خليه خفيف، والعشاء اختياري إذا ما في جوع حقيقي";
    }

